#define WIZ_BOX(n) ((((wiz_val)(n)) << 1) | 1)
#define WIZ_UNBOX(v) ((v) >> 1)
#define WIZ_IS_SCALAR(v) ((v) & 1)
#define WIZ_MAX_SMALL (((uintptr_t)1 << 62) - 1)

enum { WIZ_TAG_FIRST_SPECIAL = 0xFFFF0000u, WIZ_TAG_CLO = 0xFFFF0000u, WIZ_TAG_BIG = 0xFFFF0001u, WIZ_TAG_RAW = 0xFFFF0002u,
       WIZ_TAG_EXT = 0xFFFF0003u, WIZ_TAG_BYTES = 0xFFFF0004u, WIZ_TAG_ARRAY = 0xFFFF0005u,
       WIZ_TAG_STR = 0xFFFF0006u, WIZ_TAG_MAP = 0xFFFF0007u, WIZ_TAG_THUNK = 0xFFFF0008u,
       WIZ_TAG_WARRAY = 0xFFFF0009u, WIZ_TAG_WMAP = 0xFFFF000Au, WIZ_TAG_ITAB = 0xFFFF000Bu };


typedef struct {
  int64_t rc;
  uint32_t tag;
  uint32_t size;
} wiz_hdr;

typedef wiz_val (*wiz_boxed_fn)(wiz_val *);

typedef struct {
  wiz_hdr h;
  wiz_val fields[];
} wiz_ctor;

typedef struct {
  wiz_hdr h; /* size = number of captured arguments */
  wiz_boxed_fn fn;
  uint32_t arity;
  wiz_val args[];
} wiz_clo;

typedef struct {
  wiz_hdr h;
  mpz_t z;
} wiz_big;

/* a memoised suspension (`memo f`): applied like a closure, it runs `f` once and keeps
   the result; `fn` is 0 once it has */
typedef struct {
  wiz_hdr h;
  wiz_val fn;
  wiz_val val;
} wiz_thunk;

/* a foreign pointer, with the function that releases it (or NULL) */
typedef struct {
  wiz_hdr h;
  void *ptr;
  void (*fin)(void *);
} wiz_ext;

/* a byte buffer */
typedef struct {
  wiz_hdr h;
  size_t len, cap;
  unsigned char *data;
} wiz_bytes;

/* an array of Wiz values */
typedef struct {
  wiz_hdr h;
  size_t len, cap;
  wiz_val *data;
} wiz_array;

/* UTF-8 text (immutable) */
typedef struct {
  wiz_hdr h;
  size_t len; /* bytes */
  char data[];
} wiz_str;

/* a hash map from text to Wiz values (open addressing) */
typedef struct {
  wiz_hdr h;
  size_t count, cap;
  wiz_val *keys; /* Str objects, or 0 for empty */
  wiz_val *vals;
} wiz_map;

/* an unboxed array of machine words (lib/WordArray.wiz): `len` elements of `width`
   bytes (1, 4 or 8) at `data`, contiguous, as C would have them */
typedef struct {
  wiz_hdr h;
  size_t len, cap;
  uint32_t width;
  void *data;
} wiz_warray;

/* a hash map from 64-bit words to Wiz values (lib/WordMap.wiz): open addressing,
   linear probing, deletion by backward shift; an empty slot has vals[i] == 0 (no Wiz
   value is 0: a scalar has bit 0 set, an object is a pointer) */
typedef struct {
  wiz_hdr h;
  size_t count, cap; /* cap: a power of two */
  uint64_t *keys;
  wiz_val *vals;
} wiz_wmap;

/* an intern table (lib/Intern.wiz): the strings by id (`String` values, owned), and a
   hash index from a string to its id + 1 (0: an empty slot) */
typedef struct {
  wiz_hdr h;
  size_t count, scap; /* ids in use; room in strs/hashes */
  size_t cap;         /* slots in the index: a power of two */
  wiz_val *strs;
  uint64_t *hashes;
  uint32_t *slots;
} wiz_itab;
